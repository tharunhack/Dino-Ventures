-- ---------------------------------------------------------------------------
-- 001_init.sql — closed-loop wallet service, double-entry ledger schema.
--
-- Money model: every amount is a BIGINT in the asset's smallest indivisible
-- unit ("minor units"). Floating point never touches a balance.
--
-- Ledger model: a transaction is a set of >= 2 ledger entries whose signed
-- amounts sum to exactly zero. Credits are positive, debits are negative.
-- Credits are never minted from nothing: every credit to a user wallet is
-- matched by a debit against a system account (TREASURY / PROMO), and every
-- spend is matched by a credit to REVENUE.
-- ---------------------------------------------------------------------------

CREATE EXTENSION IF NOT EXISTS pgcrypto;

DO $do$ BEGIN
  CREATE TYPE account_kind AS ENUM ('user', 'system');
EXCEPTION WHEN duplicate_object THEN NULL; END $do$;

DO $do$ BEGIN
  CREATE TYPE transaction_kind AS ENUM ('topup', 'bonus', 'spend', 'adjustment');
EXCEPTION WHEN duplicate_object THEN NULL; END $do$;

DO $do$ BEGIN
  CREATE TYPE idempotency_status AS ENUM ('in_progress', 'completed');
EXCEPTION WHEN duplicate_object THEN NULL; END $do$;

-- --------------------------------------------------------------------------
-- Reference data
-- --------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS assets (
  id          smallint     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        text         NOT NULL UNIQUE,
  name        text         NOT NULL,
  -- Number of decimal places the asset is displayed with. Gold Coins are
  -- whole units (scale 0); an asset with scale 2 stores 1.00 as 100.
  scale       smallint     NOT NULL DEFAULT 0 CHECK (scale BETWEEN 0 AND 8),
  is_active   boolean      NOT NULL DEFAULT true,
  created_at  timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT assets_code_format CHECK (code ~ '^[A-Z][A-Z0-9_]{1,31}$')
);

CREATE TABLE IF NOT EXISTS users (
  id            uuid         PRIMARY KEY DEFAULT gen_random_uuid(),
  external_ref  text         NOT NULL UNIQUE,
  display_name  text         NOT NULL,
  email         text         UNIQUE,
  status        text         NOT NULL DEFAULT 'active'
                             CHECK (status IN ('active', 'suspended', 'closed')),
  created_at    timestamptz  NOT NULL DEFAULT now()
);

-- --------------------------------------------------------------------------
-- Accounts — one per (owner, asset). System accounts have no owner.
-- --------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS accounts (
  id              bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asset_id        smallint      NOT NULL REFERENCES assets (id),
  kind            account_kind  NOT NULL,
  owner_id        uuid          REFERENCES users (id),
  -- Stable handle for system accounts ('TREASURY', 'PROMO', 'REVENUE').
  -- For user wallets this is a human label only.
  name            text          NOT NULL,
  -- System source accounts are allowed to run negative: a negative TREASURY
  -- balance is exactly the quantity of credits in circulation.
  allow_negative  boolean       NOT NULL DEFAULT false,
  created_at      timestamptz   NOT NULL DEFAULT now(),

  CONSTRAINT accounts_owner_matches_kind CHECK (
    (kind = 'user'   AND owner_id IS NOT NULL) OR
    (kind = 'system' AND owner_id IS NULL)
  )
);

-- A user holds at most one wallet per asset, and a system account name is
-- unique per asset. Partial indexes keep the two namespaces independent.
CREATE UNIQUE INDEX IF NOT EXISTS accounts_user_wallet_uniq
  ON accounts (owner_id, asset_id) WHERE kind = 'user';

CREATE UNIQUE INDEX IF NOT EXISTS accounts_system_name_uniq
  ON accounts (asset_id, name) WHERE kind = 'system';

-- --------------------------------------------------------------------------
-- Cached balances — the hot row every transaction locks.
--
-- The authoritative balance is SUM(ledger_entries.amount); this table is a
-- maintained cache so reads and overdraft checks are O(1). It is only ever
-- written inside the same transaction as the entries that move it, so the two
-- cannot drift. `allow_negative` is denormalised from accounts purely so the
-- non-negative rule can be a CHECK constraint rather than application trust.
-- --------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS account_balances (
  account_id      bigint       PRIMARY KEY REFERENCES accounts (id) ON DELETE CASCADE,
  asset_id        smallint     NOT NULL REFERENCES assets (id),
  balance         bigint       NOT NULL DEFAULT 0,
  allow_negative  boolean      NOT NULL DEFAULT false,
  -- Bumped on every write; lets clients detect staleness and makes an
  -- optimistic-locking path available without a schema change.
  version         bigint       NOT NULL DEFAULT 0,
  updated_at      timestamptz  NOT NULL DEFAULT now(),

  CONSTRAINT account_balances_never_negative
    CHECK (allow_negative OR balance >= 0)
);

-- Every account gets its balance row at creation, so "account exists but has
-- no balance row" is not a state the application has to defend against.
CREATE OR REPLACE FUNCTION create_account_balance() RETURNS trigger
LANGUAGE plpgsql AS $fn$
BEGIN
  INSERT INTO account_balances (account_id, asset_id, balance, allow_negative)
  VALUES (NEW.id, NEW.asset_id, 0, NEW.allow_negative)
  ON CONFLICT (account_id) DO NOTHING;
  RETURN NEW;
END $fn$;

DROP TRIGGER IF EXISTS accounts_create_balance ON accounts;
CREATE TRIGGER accounts_create_balance
  AFTER INSERT ON accounts
  FOR EACH ROW EXECUTE FUNCTION create_account_balance();

-- Keep the denormalised flag honest if an account is ever reconfigured.
CREATE OR REPLACE FUNCTION sync_balance_allow_negative() RETURNS trigger
LANGUAGE plpgsql AS $fn$
BEGIN
  UPDATE account_balances
     SET allow_negative = NEW.allow_negative
   WHERE account_id = NEW.id;
  RETURN NEW;
END $fn$;

DROP TRIGGER IF EXISTS accounts_sync_allow_negative ON accounts;
CREATE TRIGGER accounts_sync_allow_negative
  AFTER UPDATE OF allow_negative ON accounts
  FOR EACH ROW EXECUTE FUNCTION sync_balance_allow_negative();

-- --------------------------------------------------------------------------
-- Transactions and ledger entries (append-only)
-- --------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS transactions (
  id          uuid              PRIMARY KEY DEFAULT gen_random_uuid(),
  kind        transaction_kind  NOT NULL,
  asset_id    smallint          NOT NULL REFERENCES assets (id),
  -- Gross movement size, always positive; the signed detail lives in entries.
  amount      bigint            NOT NULL CHECK (amount > 0),
  -- Caller's own handle for the event (payment id, order id, campaign id).
  reference   text,
  metadata    jsonb             NOT NULL DEFAULT '{}'::jsonb,
  created_at  timestamptz       NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS transactions_created_at_idx
  ON transactions (created_at DESC);
CREATE INDEX IF NOT EXISTS transactions_reference_idx
  ON transactions (reference) WHERE reference IS NOT NULL;

CREATE TABLE IF NOT EXISTS ledger_entries (
  id              bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_id  uuid         NOT NULL REFERENCES transactions (id),
  account_id      bigint       NOT NULL REFERENCES accounts (id),
  asset_id        smallint     NOT NULL REFERENCES assets (id),
  -- Signed: positive credits the account, negative debits it.
  amount          bigint       NOT NULL CHECK (amount <> 0),
  -- Balance of account_id immediately after this entry was applied. Lets the
  -- ledger be audited without replaying it from the beginning.
  balance_after   bigint       NOT NULL,
  created_at      timestamptz  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ledger_entries_account_idx
  ON ledger_entries (account_id, id DESC);
CREATE INDEX IF NOT EXISTS ledger_entries_transaction_idx
  ON ledger_entries (transaction_id);

-- The double-entry invariant, enforced by the database rather than trusted to
-- the application: entries for a transaction must net to zero and there must
-- be at least two of them. DEFERRABLE so the individual INSERTs inside a
-- transaction are not each required to balance on their own.
CREATE OR REPLACE FUNCTION assert_transaction_balances() RETURNS trigger
LANGUAGE plpgsql AS $fn$
DECLARE
  net  bigint;
  legs integer;
BEGIN
  SELECT COALESCE(SUM(amount), 0), COUNT(*)
    INTO net, legs
    FROM ledger_entries
   WHERE transaction_id = NEW.transaction_id;

  IF legs < 2 THEN
    RAISE EXCEPTION 'transaction % has % ledger entry/entries; double-entry requires at least 2',
      NEW.transaction_id, legs
      USING ERRCODE = 'check_violation';
  END IF;

  IF net <> 0 THEN
    RAISE EXCEPTION 'transaction % does not balance: entries net to %',
      NEW.transaction_id, net
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NULL;
END $fn$;

DROP TRIGGER IF EXISTS ledger_entries_must_balance ON ledger_entries;
CREATE CONSTRAINT TRIGGER ledger_entries_must_balance
  AFTER INSERT ON ledger_entries
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION assert_transaction_balances();

-- The ledger is append-only. Corrections are posted as reversing entries.
CREATE OR REPLACE FUNCTION reject_ledger_mutation() RETURNS trigger
LANGUAGE plpgsql AS $fn$
BEGIN
  RAISE EXCEPTION 'ledger_entries is append-only; post a reversing entry instead'
    USING ERRCODE = 'restrict_violation';
END $fn$;

DROP TRIGGER IF EXISTS ledger_entries_append_only ON ledger_entries;
CREATE TRIGGER ledger_entries_append_only
  BEFORE UPDATE OR DELETE ON ledger_entries
  FOR EACH ROW EXECUTE FUNCTION reject_ledger_mutation();

-- --------------------------------------------------------------------------
-- Idempotency
--
-- One row per client-supplied key. The PRIMARY KEY is what makes a retry safe:
-- a duplicate INSERT blocks on the unique index until the first request commits
-- or rolls back, so two concurrent retries can never both post a transaction.
-- --------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS idempotency_keys (
  key             text                PRIMARY KEY,
  endpoint        text                NOT NULL,
  -- Fingerprint of the request body. A key replayed with different arguments
  -- is a client bug and is rejected rather than silently answered.
  request_hash    text                NOT NULL,
  status          idempotency_status  NOT NULL DEFAULT 'in_progress',
  transaction_id  uuid                REFERENCES transactions (id),
  response_code   smallint,
  response_body   jsonb,
  created_at      timestamptz         NOT NULL DEFAULT now(),
  completed_at    timestamptz
);

CREATE INDEX IF NOT EXISTS idempotency_keys_created_at_idx
  ON idempotency_keys (created_at);

-- --------------------------------------------------------------------------
-- Read helpers
-- --------------------------------------------------------------------------

-- Authoritative balance recomputed from the ledger. The reconciliation
-- endpoint compares this against account_balances to prove the cache is sound.
CREATE OR REPLACE VIEW ledger_balances AS
  SELECT a.id                       AS account_id,
         a.asset_id,
         COALESCE(SUM(e.amount), 0) AS balance,
         COUNT(e.id)                AS entry_count
    FROM accounts a
    LEFT JOIN ledger_entries e ON e.account_id = a.id
   GROUP BY a.id, a.asset_id;
